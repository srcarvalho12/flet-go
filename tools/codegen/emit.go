const header = "// Code generated by tools/codegen from the Flet %s sources. DO NOT EDIT.\n\n"

type writer struct {
	bytes.Buffer
}

func (w *writer) p(format string, args ...any) {
	fmt.Fprintf(&w.Buffer, format, args...)
	w.WriteByte('\n')
}

var rstRole = regexp.MustCompile(":\\w+(?::\\w+)?:`~?([^`]+)`")
var spaces = regexp.MustCompile(`\s+`)

// doc writes a Go comment from a Python docstring (first paragraph only).
func (w *writer) doc(indent, prefix, text string) {
	text = strings.TrimSpace(text)
	if i := strings.Index(text, "\n\n"); i >= 0 {
		text = text[:i]
	}
	text = rstRole.ReplaceAllString(text, "`$1`")
	text = strings.ReplaceAll(text, "flet.", "")
	text = strings.ReplaceAll(text, "\\\n", " ")
	text = strings.TrimSpace(spaces.ReplaceAllString(text, " "))
	if text == "" {
		if prefix != "" {
			w.p("%s// %s", indent, strings.TrimSpace(prefix))
		}
		return
	}
	line := indent + "//"
	for _, word := range strings.Fields(prefix + text) {
		if len(line)+1+len(word) > 90 && line != indent+"//" {
			w.p("%s", line)
			line = indent + "//"
		}
		line += " " + word
	}
	w.p("%s", line)
}

func writeGo(path string, w *writer) error {
	src, err := format.Source(w.Bytes())
	if err != nil {
		os.WriteFile(path+".broken", w.Bytes(), 0o644)
		return fmt.Errorf("format %s: %w", path, err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, src, 0o644)
}

func sortedNames[T any](m map[string]T) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// ---------- enums ----------

func (m *model) emitEnums(out string) error {
	w := &writer{}
	w.p(header+"package flet", m.spec.FletVersion)
	for _, name := range sortedNames(m.enums) {
		c := m.enums[name]
		base := enumValueKind(c)
		w.doc("", name+": ", c.Doc)
		w.p("type %s %s", name, base)
		w.p("")
		w.p("const (")
		for _, mem := range c.Members {
			w.doc("\t", "", mem.Doc)
			switch v := mem.Value.(type) {
			case string:
				w.p("\t%s %s = %q", enumConst(name, mem.Name), name, v)
			case float64:
				w.p("\t%s %s = %d", enumConst(name, mem.Name), name, int64(v))
			}
		}
		w.p(")")
		w.p("")
	}
	return writeGo(filepath.Join(out, "enums_gen.go"), w)
}

// ---------- props encoding ----------

// emitEncode writes the code that puts field f of receiver r into map "m".
func emitEncode(w *writer, r string, f *field, key string) {
	v := r + "." + f.goName
	k := fmt.Sprintf("%q", key)
	switch f.typ.kind {
	case kScalar, kEnum, kColor, kIcon:
		switch {
		case f.pointer && f.override != "":
			w.p("if %s != nil { m[%s] = *%s } else { m[%s] = %s }", v, k, v, k, f.override)
		case f.pointer:
			w.p("if %s != nil { m[%s] = *%s }", v, k, v)
		case f.required || !f.pointer && f.override != "" && f.override == zeroOf(f.typ):
			w.p("m[%s] = %s", k, v)
		case f.override != "":
			w.p("if %s != %s { m[%s] = %s } else { m[%s] = %s }", v, zeroOf(f.typ), k, v, k, f.override)
		default:
			w.p("setIf(m, %s, %s)", k, v)
		}
	case kDuration:
		w.p("if %s != 0 { m[%s] = %s.Milliseconds() }", v, k, v)
	case kValue:
		w.p("if %s != nil { m[%s] = %s.toMap() }", v, k, v)
	case kSlice:
		w.p("if len(%s) > 0 { m[%s] = slices.Clone(%s) }", v, k, v)
	case kValueSlice:
		w.p("if len(%s) > 0 { l := make([]any, len(%s)); for i, x := range %s { l[i] = x.toMap() }; m[%s] = l }", v, v, v, k)
	case kMap:
		w.p("if len(%s) > 0 { m[%s] = maps.Clone(%s) }", v, k, v)
	case kAny:
		w.p("if %s != nil { m[%s] = encodeAny(%s) }", v, k, v)
	case kStrOrControl, kIconOrCtrl:
		w.p("if %s != nil { if _, ok := %s.(Control); !ok { m[%s] = encodeAny(%s) } }", v, v, k, v)
	case kHandler:
		w.p("if %s != nil { m[%s] = true }", v, k)
	}
}

func zeroOf(t gtype) string {
	switch t.goTyp {
	case "string", "Color":
		return `""`
	case "bool":
		return "false"
	}
	if t.kind == kEnum {
		return `""`
	}
	return "0"
}

func fieldDecl(w *writer, f *field, tag bool) {
	w.doc("\t", f.goName+": ", f.Doc)
	if tag {
		w.p("\t%s %s `msgpack:\"%s,omitempty\"`", f.goName, f.typ.goTyp, f.wireName())
	} else {
		w.p("\t%s %s", f.goName, f.typ.goTyp)
	}
}

// ---------- value types ----------

func (m *model) emitValues(out string) error {
	w := &writer{}
	w.p(header+"package flet\n\nimport (\n\"maps\"\n\"slices\"\n\"time\"\n)\n\nvar _ = maps.Clone[map[string]any]\nvar _ = slices.Clone[[]string]\nvar _ time.Duration", m.spec.FletVersion)
	for _, name := range sortedNames(m.values) {
		c := m.values[name]
		fs := m.fields(name, nil)
		w.doc("", name+": ", c.Doc)
		w.p("type %s struct {", name)
		for _, f := range fs {
			if f.typ.kind == kControl || f.typ.kind == kControls || f.typ.kind == kHandler {
				continue
			}
			fieldDecl(w, f, true)
		}
		w.p("}")
		w.p("")
		w.p("func (v *%s) toMap() map[string]any {", name)
		w.p("if v == nil { return nil }")
		w.p("m := map[string]any{}")
		for _, f := range fs {
			if f.typ.kind == kControl || f.typ.kind == kControls || f.typ.kind == kHandler {
				continue
			}
			emitEncode(w, "v", f, f.Name)
		}
		w.p("return m")
		w.p("}")
		w.p("")
	}
	return writeGo(filepath.Join(out, "values_gen.go"), w)
}

// ---------- events ----------

func (m *model) emitEvents(out string) error {
	w := &writer{}
	w.p(header+"package flet\n\nimport \"time\"\n\nvar _ time.Duration", m.spec.FletVersion)
	for _, name := range sortedNames(m.events) {
		c := m.events[name]
		fs := m.fields(name, map[string]bool{"Event": true})
		w.doc("", name+": ", c.Doc)
		w.p("type %s struct {", name)
		w.p("\tEvent `msgpack:\"-\"`")
		for _, f := range fs {
			if f.typ.kind == kControl || f.typ.kind == kControls || f.typ.kind == kHandler ||
				f.typ.kind == kStrOrControl || f.typ.kind == kIconOrCtrl {
				continue
			}
			if f.pointer {
				// Events are only decoded: plain values are enough.
				f.typ.goTyp = strings.TrimPrefix(f.typ.goTyp, "*")
			}
			fieldDecl(w, f, true)
		}
		w.p("}")
		w.p("")
	}
	return writeGo(filepath.Join(out, "events_gen.go"), w)
}

// ---------- controls ----------

func (m *model) emitControls(out string) error {
	w := &writer{}
	w.p(header+"package flet\n\nimport (\n\"maps\"\n\"slices\"\n\"time\"\n)\n\nvar _ = maps.Clone[map[string]any]\nvar _ = slices.Clone[[]string]\nvar _ time.Duration", m.spec.FletVersion)
	for _, name := range sortedNames(m.controls) {
		c := m.controls[name]
		fs := m.fields(name, nil)
		w.doc("", name+": ", c.Doc)
		w.p("type %s struct {", name)
		w.p("\tcontrolBase")
		for _, f := range fs {
			fieldDecl(w, f, false)
		}
		w.p("}")
		w.p("")
		w.p("func (c *%s) kind() string { return %q }", name, c.DartName)
		w.p("")
		if m.isA(name, "DialogControl") {
			w.p("func (c *%s) openField() *bool { return &c.Open }", name)
			w.p("")
		}

		w.p("func (c *%s) props() map[string]any {", name)
		w.p("m := map[string]any{}")
		for _, f := range fs {
			if f.typ.kind != kControl && f.typ.kind != kControls {
				emitEncode(w, "c", f, f.Name)
			}
		}
		w.p("return m")
		w.p("}")
		w.p("")

		var lists, slots, handlers []*field
		for _, f := range fs {
			switch f.typ.kind {
			case kControls:
				lists = append(lists, f)
			case kControl, kStrOrControl, kIconOrCtrl:
				slots = append(slots, f)
			case kHandler:
				handlers = append(handlers, f)
			}
		}
		if len(lists) > 0 {
			w.p("func (c *%s) lists() map[string][]Control {", name)
			w.p("return map[string][]Control{")
			for _, f := range lists {
				w.p("%q: c.%s,", f.Name, f.goName)
			}
			w.p("}")
			w.p("}")
			w.p("")
		}
		if len(slots) > 0 {
			w.p("func (c *%s) slots() map[string]Control {", name)
			w.p("s := map[string]Control{}")
			for _, f := range slots {
				if f.typ.kind == kControl {
					w.p("if c.%s != nil { s[%q] = c.%s }", f.goName, f.Name, f.goName)
				} else {
					w.p("if v, ok := c.%s.(Control); ok { s[%q] = v }", f.goName, f.Name)
				}
			}
			w.p("return s")
			w.p("}")
			w.p("")
		}
		// Properties the client can change (e.g. TextField.value as the user types).
		var settable []*field
		for _, f := range fs {
			switch f.typ.kind {
			case kScalar, kEnum, kColor, kIcon:
				settable = append(settable, f)
			}
		}
		if len(settable) > 0 {
			w.p("func (c *%s) applyProps(p map[string]any) {", name)
			w.p("for k, v := range p {")
			w.p("switch k {")
			for _, f := range settable {
				if f.pointer {
					w.p("case %q: assignPtr(&c.%s, v)", f.Name, f.goName)
				} else {
					w.p("case %q: assign(&c.%s, v)", f.Name, f.goName)
				}
			}
			w.p("}")
			w.p("}")
			w.p("}")
			w.p("")
		}

		if len(handlers) > 0 {
			w.p("func (c *%s) handleEvent(e *Event) {", name)
			w.p("switch e.Name {")
			for _, f := range handlers {
				w.p("case %q:", strings.TrimPrefix(f.Name, "on_"))
				w.p("if c.%s != nil {", f.goName)
				if f.typ.event == "" {
					w.p("c.%s(e)", f.goName)
				} else {
					w.p("ev := &%s{Event: *e}", f.typ.event)
					w.p("decodeEvent(e, ev)")
					w.p("c.%s(ev)", f.goName)
				}
				w.p("}")
			}
			w.p("}")
			w.p("}")
			w.p("")
		}
	}
	return writeGo(filepath.Join(out, "controls_gen.go"), w)
}

// allMethods returns the client methods of every generated control.
func (m *model) allMethods() map[string][]*method {
	all := map[string][]*method{}
	for _, name := range sortedNames(m.controls) {
		names := map[string]bool{}
		report := m.report
		m.report = map[string]int{} // fields were already counted
		for _, f := range m.fields(name, nil) {
			names[f.goName] = true
		}
		m.report = report
		if ms := m.methods(name, names); len(ms) > 0 {
			all[name] = ms
		}
	}
	m.assignOptionNames(all)
	return all
}

// ---------- colors and icons ----------

func (m *model) emitColors(out string) error {
	w := &writer{}
	w.p(header+"// Package colors has the named colors understood by the Flet client.\npackage colors\n\nimport flet \"github.com/srcarvalho12/flet-go\"", m.spec.FletVersion)
	for _, enum := range []struct{ name, prefix string }{{"Colors", ""}, {"CupertinoColors", "Cupertino"}} {
		c := m.classes[enum.name]
		if c == nil {
			continue
		}
		w.p("const (")
		for _, mem := range c.Members {
			if s, ok := mem.Value.(string); ok {
				w.p("%s%s flet.Color = %q", enum.prefix, goName(strings.ToLower(mem.Name)), s)
			}
		}
		w.p(")")
	}
	return writeGo(filepath.Join(out, "colors", "colors_gen.go"), w)
}

func (m *model) emitIcons(specDir, out string) error {
	w := &writer{}
	w.p(header+"// Package icons has the Material and Cupertino icons understood by the Flet client.\npackage icons\n\nimport flet \"github.com/srcarvalho12/flet-go\"", m.spec.FletVersion)
	for _, set := range []struct{ file, prefix string }{{"icons.json", ""}, {"cupertino_icons.json", "Cupertino"}} {
		b, err := os.ReadFile(filepath.Join(specDir, set.file))
		if err != nil {
			return err
		}
		var icons map[string]int64
		if err := json.Unmarshal(b, &icons); err != nil {
			return err
		}
		w.p("const (")
		for _, name := range sortedNames(icons) {
			w.p("%s%s flet.IconData = %d", set.prefix, goName(strings.ToLower(name)), icons[name])
		}
		w.p(")")
	}
	return writeGo(filepath.Join(out, "icons", "icons_gen.go"), w)
}
